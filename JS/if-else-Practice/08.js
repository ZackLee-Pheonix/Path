// 8. Оценка температуры: Напишите программу, которая в зависимости от
// температуры на улице выводит соответствующее сообщение (например, "Жарко",
// "Холодно", "Тепло").

let temp = prompt("Temperature: ")

if (temp >= 0 && temp < 10) {
    console.log("Холодно")
} else if (temp >= 10 && temp < 20) {
    console.log("Тепло")
} if (temp >= 20 && temp < 30) {
    console.log("Жарко")
}