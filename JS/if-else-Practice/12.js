// 12. Определение категории по возрасту: Напишите программу, которая
// классифицирует человека по возрасту (например, "Ребёнок", "Подросток",
// "Взрослый", "Пенсионер").

let age = prompt("Age: ")

if (age >= 1 && age <= 12) {
    console.log("Ребёнок")
} else if (age >= 13 && age <= 18) {
    console.log("Подросток")
} else if (age >= 19 && age <= 55) {
    console.log("Взрослый")
} else if (age >= 56 && age <= 100) {
    console.log("Пенсионер")
}