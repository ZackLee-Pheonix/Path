// 18. Рейтинг по баллам: Напишите программу, которая выводит рейтинг на основе
// баллов, полученных студентом (например, "Хорошо", "Отлично",
// "Удовлетворительно").

let score = prompt("Score: ")

if (score >= 90) {
    console.log("Отлично")
} else if (score >= 80 && score < 90) {
    console.log("Хорошо")
} else if (score >= 70 && score < 80) {
    console.log("Удовлетворительно")
}