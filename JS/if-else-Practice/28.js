// 28. Выбор метода оплаты: Напишите программу, которая предлагает разные способы
// оплаты в зависимости от суммы покупки (например, "Карта", "Наличные",
// "Криптовалюта").

let check = prompt("Check: ")

if (check <= 1000) {
    console.log("Карта")
} else if (check <= 10000 && check > 1000) {
    console.log("Наличные")
} else if (check > 10000) {
    console.log("Криптовалюта")
}